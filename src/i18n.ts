export function tr(text:string,values:Record<string,string|number>={}):string {
 let translated=text;
 if(!language.startsWith('ko')){
  translated=english[text]??text;
  for(const prefix of ['잘못된 설정: ','알 수 없는 설정: ','알 수 없는 옵션: ']){
   if(text.startsWith(prefix)){translated=english[prefix]+text.slice(prefix.length);break;}
  }
 }
 return translated.replace(/\{(\w+)\}/g,(match:string,key:string)=>String(values[key]??match));
}

